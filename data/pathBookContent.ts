export type PathBookKind =
  | 'bruxaria'
  | 'cacada'
  | 'esperanca'
  | 'patronos'
  | 'violencia'
  | 'anti-cacada'

export type PathBookEntry = {
  id: string
  name: string
  description: string
  cost: number
  systemType: 'path'
  sourceGroup: string
  activationType: 'passiva' | 'condicional' | 'complexa' | 'ativa'
  pathKind: PathBookKind
  variant?: string
  bonuses?: {
    attributes?: Record<string, number>
    skills?: Record<string, number>
    corpo?: number
    mente?: number
    folego?: number
    mana?: number
    attack?: number
    damage?: number
    penetration?: number
    crit?: number
    maxDamage?: number
  }
  requirementsText?: string
  previousIds?: string[]
  meta?: Record<string, unknown>
}

function pe(
  partial: Omit<PathBookEntry, 'systemType' | 'activationType'> & {
    activationType?: PathBookEntry['activationType']
  },
): PathBookEntry {
  return {
    systemType: 'path',
    activationType: partial.activationType ?? 'complexa',
    ...partial,
  }
}

